    /** The categories, loaded once (drawable emoji only). */
    val categories: List<Category> by lazy {
        val paint = Paint()
        data.mapIndexed { i, (name, s) ->
            Category(name, icons[i], s.split(' ').filter { it.isNotBlank() && paint.hasGlyph(it) }.distinct())
        }
    }

    private const val MAX_RECENT = 32

    fun recent(): List<String> = Prefs.recentEmoji.split(' ').filter { it.isNotBlank() }

    fun used(e: String) {
        Prefs.recentEmoji = (listOf(e) + recent().filter { it != e }).take(MAX_RECENT).joinToString(" ")
    }
